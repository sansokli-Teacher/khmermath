def opts(*xs): return [M(str(x)) for x in xs]


def fr(x):
    x = F(x)
    if x.denominator == 1: return M(str(x.numerator))
    return M(('-' if x < 0 else '') + r'\dfrac{%d}{%d}' % (abs(x.numerator), x.denominator))


def money(x, dp=2):
    return ('%.*f' % (dp, float(x)))


