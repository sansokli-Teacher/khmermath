def _pascal(rows):
    out = ["<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 360 %d' width='360' height='%d'>" % (30 + 26 * rows, 30 + 26 * rows)]
    for r in range(rows):
        for c in range(r + 1):
            x = 180 + (2 * c - r) * 26
            y = 24 + 26 * r
            out.append("<text x='%d' y='%d' text-anchor='middle' font-family='Times New Roman, serif' font-size='15' fill='#1e40af'>%d</text>" % (x, y, comb(r, c)))
    out.append('</svg>')
    return ''.join(out)


