# ----------------------------------------------------------------------------- number helpers
def _L(x):
    return latex(x).replace('\\frac', '\\dfrac')


def val(z):
    z = nsimplify(simplify(expand_complex(expand(z))))
    return z


def fz(z):
    """complex number -> LaTeX 'a + bi' (no \\( \\) wrapper)."""
    z = val(z)
    a, b = simplify(sre(z)), simplify(sim(z))
    if b == 0:
        return _L(a)
    neg = b.could_extract_minus_sign()
    bb = -b if neg else b
    bs = '' if bb == 1 else _L(bb)
    if a == 0:
        return ('-' if neg else '') + bs + 'i'
    return _L(a) + (' - ' if neg else ' + ') + bs + 'i'


def Z(z):
    return M(fz(z))


def Zu(z, unit):
    return M(fz(z) + '\\ ' + unit)


def pt(z):
    z = val(z)
    return M('(%s,\\ %s)' % (_L(sre(z)), _L(sim(z))))


def wrongs_from(right, cands, k=3):
    """k distinct wrong strings (as numbers) that differ from `right` by value."""
    out, seen = [], {fz(right)}
    for c in cands:
        s = fz(c)
        if s not in seen:
            seen.add(s)
            out.append(c)
        if len(out) == k:
            break
    assert len(out) == k, (fz(right), [fz(c) for c in cands])
    return out


def cz(a, b=0):
    return a + b * I


