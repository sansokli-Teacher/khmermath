def fig_parabola(fn, x0, x1, y0, y1, xlabel='x (m)', ylabel='y (m)',
                 xticks=None, yticks=None, title='',
                 dots_data=None, segs_data=None, notes_data=None,
                 curve_x_range=None):
    """Draw a parabola curve with P.G; strips false 'O' and adds '//' if (x0, y0) != (0, 0)."""
    W, H = 290, 165
    kx = W / (x1 - x0)
    ky = H / (y1 - y0)
    sx = lambda x: (x - x0) * kx
    sy = lambda y: (y - y0) * ky

    cx0, cx1 = curve_x_range if curve_x_range is not None else (x0, x1)
    px0 = max(0.0, sx(cx0))
    px1 = min(float(W), sx(cx1))
    curves = [(lambda px_: sy(fn(x0 + px_ / kx)), px0, px1, P.K.BLUE)]

    dots = []
    if dots_data:
        for x, y, lbl, dx, dy, col in dots_data:
            dots.append((sx(x), sy(y), lbl, dx, dy, col))

    segs = []
    if segs_data:
        for xa, ya, xb, yb, col, dashed in segs_data:
            segs.append((sx(xa), sy(ya), sx(xb), sy(yb), col, dashed))

    notes = []
    if xticks is None:
        xticks = [x0, (x0 + x1) / 2, x1]
    if yticks is None:
        yticks = [y0, (y0 + y1) / 2, y1]
    for xv in xticks:
        xp = sx(xv)
        segs.append((xp, -4, xp, 4, P.K.AXIS, False))
        lbl = str(int(xv)) if xv == int(xv) else f'{xv:g}'
        notes.append((xp, 0, lbl, 0, 18, P.K.AXIS, False))
    for yv in yticks:
        yp = sy(yv)
        segs.append((-4, yp, 4, yp, P.K.AXIS, False))
        lbl = str(int(yv)) if yv == int(yv) else f'{yv:g}'
        notes.append((0, yp, lbl, -26, 4, P.K.AXIS, False))

    if notes_data:
        for x, y, txt, dx, dy, col, bold in notes_data:
            notes.append((sx(x), sy(y), txt, dx, dy, col, bold))

    if title:
        notes.append((W * 0.55, H - 6, title, 0, 0, P.K.BLUE, False))

    if x0 > 0:
        segs.append((8, -5, 13, 5, P.K.AXIS, False))
        segs.append((13, -5, 18, 5, P.K.AXIS, False))
    if y0 > 0:
        segs.append((-5, 8, 5, 13, P.K.AXIS, False))
        segs.append((-5, 13, 5, 18, P.K.AXIS, False))

    ylab_arg = ylabel
    if len(ylabel) > 1:
        ylab_arg = ''
        notes.append((0, H, ylabel, 32, 5, P.K.INK, True))

    svg = P.G(W, H, curves, segs=segs, dots=dots, notes=notes, xlabel=xlabel, ylabel=ylab_arg, pad=48)
    if x0 != 0 or y0 != 0:
        svg = re.sub(r"<text[^>]*>O</text>", '', svg, count=1)
    return svg


