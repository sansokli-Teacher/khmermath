def PW(*pairs):
    """cases environment from (sympy expr, condition-latex) pairs."""
    return '\\begin{cases} ' + ' \\\\ '.join('%s & \\text{បើ } %s' % (_L(e) if not isinstance(e, str) else e, c) for e, c in pairs) + ' \\end{cases}'


def one_sided(f, c, d):
    mp.mp.dps = 60
    h = mp.mpf(10) ** -25
    return f(mp.mpf(c) + (h if d == '+' else -h))


def close(a, b, e=1e-9):
    return abs(mp.mpf(a) - mp.mpf(b)) < e


