def F(a, b=None):
    return Fraction(a, b) if b is not None else Fraction(str(a))


def ols(pts):
    """Exact OLS regression and Pearson r helpers from a list of (x, y) pairs."""
    n = len(pts)
    xs = [F(p[0]) for p in pts]
    ys = [F(p[1]) for p in pts]
    sx = sum(xs)
    sy = sum(ys)
    sxy = sum(x * y for x, y in zip(xs, ys))
    sx2 = sum(x * x for x in xs)
    sy2 = sum(y * y for y in ys)
    num = n * sxy - sx * sy
    denx = n * sx2 - sx * sx
    deny = n * sy2 - sy * sy
    a = num / denx
    b = (sy - a * sx) / n
    r = float(num) / math.sqrt(float(denx * deny)) if denx * deny != 0 else 0.0
    return {
        'n': n, 'sx': sx, 'sy': sy, 'sxy': sxy, 'sx2': sx2, 'sy2': sy2,
        'num': num, 'denx': denx, 'deny': deny, 'a': a, 'b': b, 'r': r,
    }


def sse(pts, m, c):
    """Exact sum of squared vertical residuals sum (y_i - (m*x_i + c))^2."""
    mf, cf = F(m), F(c)
    return sum((F(y) - (mf * F(x) + cf)) ** 2 for x, y in pts)


def fig_scatter(pts, x0, x1, y0, y1, xlabel='x', ylabel='y', xticks=None, yticks=None,
                title='', line_fn=None, mean_pt=None, mean_off=(10, -8)):
    """Coordinate scatter plot using P.G; strips false 'O' and draws '//' axis breaks when origin != (0, 0)."""
    W, H = 290, 165
    kx = W / (x1 - x0)
    ky = H / (y1 - y0)
    sx = lambda x: (x - x0) * kx
    sy = lambda y: (y - y0) * ky
    dots = [(sx(x), sy(y), '', 0, 0, P.K.BLUE) for x, y in pts]
    if mean_pt:
        dots.append((sx(mean_pt[0]), sy(mean_pt[1]), 'M', mean_off[0], mean_off[1], P.K.RED))
    curves = []
    if line_fn is not None:
        curves.append((lambda px_: sy(line_fn(x0 + px_ / kx)), 0, W, P.K.AMBER))
    segs = []
    notes = []
    if xticks is None:
        xticks = [x0, (x0 + x1) / 2, x1]
    if yticks is None:
        yticks = [y0, (y0 + y1) / 2, y1]
    for xv in xticks:
        xp = sx(xv)
        segs.append((xp, -4, xp, 4, P.K.AXIS, False))
        lbl = str(int(xv)) if xv == int(xv) else f'{xv:g}'
        notes.append((xp, 0, lbl, 0, 18, P.K.AXIS, False))
    for yv in yticks:
        yp = sy(yv)
        segs.append((-4, yp, 4, yp, P.K.AXIS, False))
        lbl = str(int(yv)) if yv == int(yv) else f'{yv:g}'
        notes.append((0, yp, lbl, -26, 4, P.K.AXIS, False))
    if title:
        notes.append((W * 0.56, H - 10, title, 0, 0, P.K.BLUE, False))
    if x0 != 0:
        segs.append((8, -5, 13, 5, P.K.AXIS, False))
        segs.append((13, -5, 18, 5, P.K.AXIS, False))
    if y0 != 0:
        segs.append((-5, 8, 5, 13, P.K.AXIS, False))
        segs.append((-5, 13, 5, 18, P.K.AXIS, False))
    ylab_arg = ylabel
    if len(ylabel) > 1:
        ylab_arg = ''
        notes.append((0, H, ylabel, 30, 5, P.K.INK, True))
    svg = P.G(W, H, curves, segs=segs, dots=dots, notes=notes, xlabel=xlabel, ylabel=ylab_arg, pad=48)
    if x0 != 0 or y0 != 0:
        svg = re.sub(r"<text[^>]*>O</text>", '', svg, count=1)
    return svg


